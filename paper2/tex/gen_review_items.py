"""paper2/tex/gen_review_items.py: write REVIEW_ITEMS.md (plain text) listing every item marked for the author's review:
CAPTION-DRAFT captions, table short titles, the DRAFT-TEXT of Appendix D, and the nine inserted figure references.
Run from the repo root with the pinned interpreter: /usr/bin/python3 paper2/tex/gen_review_items.py"""
import re
import sys
from pathlib import Path

TEX = Path(__file__).resolve().parent
sys.path.insert(0, str(TEX))
import build_tex as B  # noqa: E402

PLAIN = [(r"\textbf{", ""), (r"\emph{", ""), (r"\texttt{", ""), (r"\times", "×"), (r"\mu", "μ"), (r"\lambda", "λ"), (r"\rho", "ρ"),
         (r"\theta", "θ"), (r"\Delta", "Δ"), (r"\delta", "δ"), (r"\to", "→"), (r"\allowbreak", ""), (r"\%", "%"), (r"\|", "‖"),
         (r"\_", "_"), (r"\,", " "), ("~", " "), (r"\max", "max"), (r"\geq", "≥"), (r"\leq", "≤"), ("--", "–")]


def plain(s):
    for a, b in PLAIN:
        s = s.replace(a, b)
    s = re.sub(r"\\ref\{([^}]+)\}", r"[\1]", s)
    s = re.sub(r"\^\{([^}]*)\}", r"^\1", s)
    s = re.sub(r"_\{([^}]*)\}", r"_\1", s)
    s = s.replace("{}", "").replace("$", "")
    s = re.sub(r"[{}]", "", s)
    return re.sub(r"\s+", " ", s).strip()


def section_of(body, needle):
    pos = body.find(needle)
    secs = [(m.start(), m.group(1)) for m in re.finditer(r"\\section\{([^}]*)\}", body)]
    sec = [n for p, n in secs if p < pos]
    return plain(sec[-1]) if sec else "?"


def main():
    body = (TEX / "body.tex").read_text()
    md = (TEX.parent / "draft" / "paper2_draft.md").read_text(encoding="utf-8")
    cap = B.captions()
    figno = {"fig:mechanism": "Figure 1", "fig:paths": "Figure 2", "fig:corrdose": "Figure 3", "fig:bspline": "Figure 4",
             "fig:synthetic": "Figure 5 (Appendix E)", "fig:where": "Figure 6 (Appendix E)", "fig:applicability": "Figure 7 (Appendix E)",
             "fig:dose": "Figure 8 (Appendix E)", "fig:uniqueness": "Figure 9 (Appendix E)",
             "fig:S1": "Figure S1", "fig:S2": "Figure S2", "fig:S3": "Figure S3"}
    out = ["# Review items for the paper 2 manuscript",
           "",
           "Generated by `paper2/tex/gen_review_items.py` from the built sources, so this file matches the PDFs.",
           "Each item is marked in the `.tex` source as noted. Text is shown as plain text, with LaTeX markup removed.", "",
           "## 1. Figure captions (`% CAPTION-DRAFT: review`)", ""]
    for lab, (name, c) in cap.items():
        where = ("main text, " + section_of(body, f"\\label{{{lab}}}")) if f"\\label{{{lab}}}" in body else "Appendix E (supplementary figures)"
        out += [f"### {figno[lab]} (`\\label{{{lab}}}`, file `{name}.pdf`)", "",
                f"- **Location:** {where}; built by `build_tex.py`, `captions()`.",
                f"- **Numbers from:** `paper2/figures/{name}.json`.", "",
                f"**Caption:** {plain(c)}", ""]
    out += ["## 2. Table short titles (`% CAPTION-DRAFT: review`; not in the draft)", ""]
    for lab, c in B.TABLE_CAPTIONS:
        out += [f"- `\\label{{{lab}}}` ({section_of(body, chr(92) + 'label{' + lab + '}')}): {plain(c)}"]
    d = B.appendix_d()
    paras = re.findall(r"\\paragraph\{([^}]*)\}(.*?)(?=\\paragraph|\\noindent|$)", d.split("% DRAFT-TEXT: review")[1], re.S)
    out += ["", "## 3. Appendix D protocol prose (`% DRAFT-TEXT: review`; new text, not in the draft)", "",
            "- **Location:** Appendix D, \"Research process\"; built by `build_tex.py`, `appendix_d()`.",
            "- The table of pre-registration, amendment and crash-record commits that follows the prose is generated from git and is not listed here.", ""]
    for h, t in paras:
        out += [f"**{plain(h)}** {plain(t)}", ""]
    out += ["## 4. Inserted figure references (the draft has two placeholders, Sections 6 and 7; `build_tex.py`, `FIG_REFS`)", ""]
    for i, (a, b) in enumerate(B.FIG_REFS, 1):
        ref = re.search("[\x01\x02]([^|]+)\\|([^\x01\x02]*)[\x01\x02]", b)
        lab, sub = ref.group(1), ref.group(2)
        pos = md.find(a); heads = [(m.start(), m.group(1)) for m in re.finditer(r"^## (.+)$", md, re.M) if m.start() < pos]
        para = md.rfind("\n\n", 0, pos); lead = re.match(r"\s*(?:- )?\*\*([^*]+)\*\*", md[para:pos + 1])
        where = f"Section {heads[-1][1]}" + (f", paragraph \"{lead.group(1)}\"" if lead else "")
        out += [f"{i}. **({figno[lab]}{sub})**: {where}. Anchor text (reference placed at its end): \"{a}\""]
    (TEX / "REVIEW_ITEMS.md").write_text("\n".join(out) + "\n")
    print((TEX / "REVIEW_ITEMS.md").read_text())


if __name__ == "__main__":
    main()
